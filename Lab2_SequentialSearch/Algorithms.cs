namespace Lab2_SequentialSearch
{
    /// <summary>
    /// Алгоритмы последовательного поиска.
    /// Массивы выделяются на 1 элемент больше: a[n] - место под барьер,
    /// барьер элементом массива не считается. Индексы с 0.
    /// Результат - индекс найденного элемента или -1, если ключ не найден.
    /// </summary>
    public static class Algorithms
    {
        /// <summary>
        /// Алгоритм A. Неоптимальный последовательный поиск
        /// (в цикле две проверки: конец массива и совпадение ключа).
        /// </summary>
        public static int SearchA(int[] a, int n, int key)
        {
            int i = 0;                 // A1. Начать с первого элемента
            while (i < n)              // A2. Проверка конца массива
            {
                if (a[i] == key)       // A3. Сравнение с ключом
                    return i;          //     успех
                i++;                   // A4. Переход к следующему элементу
            }
            return -1;                 // неудача
        }

        /// <summary>
        /// Алгоритм B. Оптимальный последовательный поиск с барьером
        /// (в цикле одна проверка). Требуется a.Length &gt; n.
        /// </summary>
        public static int SearchB(int[] a, int n, int key)
        {
            a[n] = key;                // B1. Барьер: ключ ставится за последним элементом
            int i = 0;                 // B2. Начать с первого элемента
            while (a[i] != key)        // B3. Сравнение с ключом (конец массива проверять не нужно)
                i++;                   // B4. Переход к следующему элементу
            return i == n ? -1 : i;    // B5. Дошли до барьера - ключа в массиве нет
        }

        /// <summary>
        /// Алгоритм C. Последовательный поиск в упорядоченном (по возрастанию) массиве
        /// с барьером K + 1. Требуется a.Length &gt; n и key &lt; int.MaxValue.
        /// При дубликатах возвращается индекс первого вхождения.
        /// </summary>
        public static int SearchC(int[] a, int n, int key)
        {
            a[n] = key + 1;            // C1. Барьер больше ключа
            int i = 0;                 // C2. Начать с первого элемента
            while (key > a[i])         // C3. Пока элементы меньше ключа
                i++;                   // C4. Переход к следующему элементу
            // C5. Остановились на первом элементе >= K: это ключ или ключа нет
            return (i < n && a[i] == key) ? i : -1;
        }
    }
}
